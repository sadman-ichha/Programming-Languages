a = -29
b = 10
print(a + b)
print(a - b)
print(a * b)
print(a / b)

# Floor division (int)
print(a // b)

# Exponent
print(2**6)  # Base = 2, exp = 5 -> 2x2x2x2x2
print(100**0.5)  # Base = 100, exp = 0.5
print(25**0.5)  # 25^0.5 = 25^1/2 = 25 ||| 25 root square = 5
print(25 ** (1/2)) # (25**0.5) same 

# modulus (remainder)
print(24 % 10)
