# Python: combining and repeating strings

first = "Sam"
last = "Roy"

# Use + to join strings.
print("Full name:", first + " " + last)
print("Name plus number:", first + " " + last + "5")

# Use * to repeat a string.
print("Repeated name:", first * 3)

digit = "5"
print("Repeated digit:", digit * 3)

# Example output:
# Full name: Sam Roy
# Name plus number: Sam Roy5
# Repeated name: SamSamSam
# Repeated digit: 555

# Key ideas:
# - Use + to join, or concatenate, strings.
# - Use * with an integer to repeat a string.
# - Subtraction, division, and multiplying strings with strings are invalid.
